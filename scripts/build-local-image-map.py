#!/usr/bin/env python3
"""Generate assets/local-images.js from the sport image registers.
Run after a register changes:  python3 -I scripts/build-local-image-map.py

Each register keeps its own basePath, so a name resolves to the sport's own folder.
A name held by two fighters is dropped, within a sport or across them: a name alone
cannot pick the right face."""
import json, unicodedata
from pathlib import Path

root = Path(__file__).resolve().parent.parent
REGISTERS = ["data/ufc-image-register.json", "data/boxing-image-register.json"]
norm = lambda s: unicodedata.normalize("NFD", s).encode("ascii", "ignore").decode().replace("‘", "'").replace("’", "'").strip().lower()

bases, m, clash = [], {}, set()
for path in REGISTERS:
    f = root / path
    if not f.exists():
        continue
    reg = json.loads(f.read_text(encoding="utf-8"))
    base = reg["basePath"]
    if base not in bases:
        bases.append(base)
    b = bases.index(base)
    kept = 0
    for r in reg["images"]:
        if not all((root / base / name).exists() for name in r["files"].values()):
            continue  # never point the site at a file that is not there
        k = norm(r["name"])
        if k in m:
            clash.add(k)
        m[k] = [r["id"], b]
        kept += 1
    print(f"{path}: {kept} with files on disk")
for k in clash:
    del m[k]  # two fighters share a name: show neither
if clash:
    print("skipped ambiguous names:", sorted(clash))

js = """/* GENERATED by scripts/build-local-image-map.py from the sport image registers. Do not edit by hand.
   Local fighter photos BEFN holds: UFC portraits (owner-cleared) and boxing press-kit
   photos (promoter-attested). Returns '' when there is no local file, so callers keep
   their existing fallback. */
(function(){
'use strict';
var MAP=%s;
var BASES=%s;
var SIZES={thumb:1,portrait:1,card:1};
function norm(s){return String(s||'').normalize('NFD').replace(/[\\u0300-\\u036f]/g,'').replace(/[\\u2018\\u2019]/g,"'").trim().toLowerCase()}
window.BEFNLocalImages={
  has:function(name){return Object.prototype.hasOwnProperty.call(MAP,norm(name))},
  url:function(name,kind){var e=MAP[norm(name)];if(!e)return '';if(!SIZES[kind])kind='thumb';return BASES[e[1]]+e[0]+'-'+kind+'.webp'}
};
})();
""" % (json.dumps(m, separators=(",", ":"), ensure_ascii=True, sort_keys=True), json.dumps(bases))
(root / "assets/local-images.js").write_text(js, encoding="utf-8")
print(len(m), "fighters mapped across", len(bases), "registers")
