#!/usr/bin/env python3
"""Generate assets/local-images.js from data/ufc-image-register.json.
Run after the register changes:  python3 -I scripts/build-local-image-map.py"""
import json, unicodedata
from pathlib import Path
root = Path(__file__).resolve().parent.parent
reg = json.loads((root / "data/ufc-image-register.json").read_text(encoding="utf-8"))
norm = lambda s: unicodedata.normalize("NFD", s).encode("ascii", "ignore").decode().replace("‘", "'").replace("’", "'").strip().lower()
m, clash = {}, set()
for r in reg["images"]:
    if not all((root / reg["basePath"] / f).exists() for f in r["files"].values()):
        continue  # never point the site at a file that is not there
    k = norm(r["name"])
    if k in m: clash.add(k)
    m[k] = r["id"]
for k in clash:
    del m[k]  # two fighters share a name: names alone cannot pick the right face, so show neither
if clash: print("skipped ambiguous names:", sorted(clash))
js = """/* GENERATED by scripts/build-local-image-map.py from data/ufc-image-register.json. Do not edit by hand.
   Local, owner-cleared fighter photos. Returns '' when there is no local file so callers keep their existing fallback. */
(function(){
'use strict';
var MAP=%s;
var BASE=%s;
var SIZES={thumb:1,portrait:1,card:1};
function norm(s){return String(s||'').normalize('NFD').replace(/[\\u0300-\\u036f]/g,'').replace(/[\\u2018\\u2019]/g,"'").trim().toLowerCase()}
window.BEFNLocalImages={
  has:function(name){return Object.prototype.hasOwnProperty.call(MAP,norm(name))},
  url:function(name,kind){var id=MAP[norm(name)];if(!id)return '';if(!SIZES[kind])kind='thumb';return BASE+id+'-'+kind+'.webp'}
};
})();
""" % (json.dumps(m, separators=(",", ":"), ensure_ascii=True, sort_keys=True), json.dumps(reg["basePath"]))
(root / "assets/local-images.js").write_text(js, encoding="utf-8")
print(len(m), "fighters mapped")
