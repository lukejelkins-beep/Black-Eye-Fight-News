import assert from 'node:assert/strict';
import {normalizePostLink,extractPostLinks,publisherOf,validMetaEmbed,mergeSourceLinks,originalStillRelevant} from '../scripts/refresh-meta-embeds.mjs';

const u=normalizePostLink('https://www.instagram.com/johnnywalker/p/Dfakkjhjz-3/?igsh=test');
assert.equal(u.url,'https://www.instagram.com/p/Dfakkjhjz-3/');
assert.equal(u.platform,'Instagram');
assert.equal(normalizePostLink('https://instagram.com/reel/DfTi2rvyg1d/').url,'https://www.instagram.com/reel/DfTi2rvyg1d/');
assert.equal(normalizePostLink('https://threads.net/@ufc/post/DWjTI0cgH5O/').url,'https://www.threads.com/@ufc/post/DWjTI0cgH5O/');
assert.equal(normalizePostLink('https://threads.com/t/C8H1eEbRQ0X').platform,'Threads');
for(const x of ['javascript:alert(1)','https://evil.example.com/p/Dfakkjhjz-3','https://instagram.com/stories/ufc/test','http://instagram.com/p/Dfakkjhjz-3','https://instagram.com:444/p/Dfakkjhjz-3'])assert.equal(normalizePostLink(x),null);
const found=extractPostLinks('<a href="https://www.instagram.com/p/Dfakkjhjz-3/?utm_source=news">Instagram</a><a href="https:\\/\\/www.threads.com\\/@ufc\\/post\\/C8H1eEbRQ0X">Threads</a><a href="https://www.instagram.com/p/Dfakkjhjz-3/">Duplicate</a>');
assert.equal(found.length,2);
assert.equal(publisherOf('https://www.mmafighting.com/ufc/test'),'MMA Fighting');
assert.equal(publisherOf('https://example.org/article'),'');
assert.equal(validMetaEmbed({type:'rich',provider_name:'Instagram',html:'<blockquote class="instagram-media">verified public post</blockquote>'},'Instagram'),true);
assert.equal(validMetaEmbed({type:'rich',provider_name:'X',html:'<blockquote>unrelated</blockquote>'},'Threads'),false);
const at='2026-11-08T07:15:00Z',article={url:'https://www.mmafighting.com/ufc/1234/post',sport:'mma',publishedAt:'2026-11-08T05:10:00Z'};
const entries=mergeSourceLinks([article],[{article,item:found[0]}],{posts:[]},at);
assert.equal(entries.length,1);
assert.equal(entries[0].originalDateUnverified,true);
assert.equal(entries[0].postedAt,undefined);
assert.equal(entries[0].role,'media');
assert.equal(entries[0].sourceLinkedAt,article.publishedAt);
assert.equal(entries[0].nativeEmbed,true);
assert.equal(mergeSourceLinks([article],[{article,item:found[0]}],{posts:entries},at).length,1);
const homepage={url:'https://www.ufc.com/',sport:'mma',publishedAt:'2026-11-08T08:28:00Z',sourceLabel:'UFC official homepage'};
const originalThread={platform:'Threads',url:'https://www.threads.com/t/DfaMxmkmyfr/'};
const firstSeen=mergeSourceLinks([homepage],[{article:homepage,item:originalThread}],{posts:[]},'2026-11-08T08:28:00Z');
assert.equal(firstSeen.length,1,'New official homepage link added once');
assert.equal(firstSeen[0].sourceLinkedAt,'2026-11-08T08:28:00Z');
const laterHome={...homepage,publishedAt:'2026-11-12T08:28:00Z'};
const stillOne=mergeSourceLinks([laterHome],[{article:laterHome,item:originalThread}],{posts:firstSeen},'2026-11-12T08:28:00Z');
assert.equal(stillOne.length,1);
assert.equal(stillOne[0].sourceLinkedAt,'2026-11-08T08:28:00Z','Repeated homepage scan does not reset post age');
const record=new Map([[originalThread.url,firstSeen[0].discoveredAt]]);
assert(originalStillRelevant(originalThread.url,record,'2026-11-15T08:28:00Z'));
assert(!originalStillRelevant(originalThread.url,record,'2026-12-07T08:29:00Z'),'Old homepage links must stop appearing live');
assert.equal(mergeSourceLinks([laterHome],[],{posts:firstSeen},'2026-12-07T08:29:00Z').length,0,'Old embeds expire from highlights');
console.log('Meta embed discovery checks passed: canonical URLs, authentic publisher provenance, no invented post timestamps or author identity.');
