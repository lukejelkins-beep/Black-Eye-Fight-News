import assert from 'node:assert/strict';
import {X_POLICY,xAccounts,accountGroups,buildQuery,monthUtc,reservePlan,
 finalizeLedger,normalizeTweets,mergeXFeed} from '../scripts/twitterapi-io-core.mjs';
import fs from 'node:fs';
const config=JSON.parse(fs.readFileSync('data/fight-talk-sources.json','utf8'));
const accounts=xAccounts(config);
assert(accounts.length>=100,'Expected broad tracked X author coverage');
const roles=new Set(accounts.map(x=>x.role));
for(const role of ['fighter','promoter','manager','media','meme'])assert(roles.has(role),'Missing '+role+' accounts');
const groups=accountGroups(config);
assert(groups.length>=12&&groups.length<=30);
assert(groups.every(g=>g.length&&g.length<=8));
assert.equal(new Set(groups.flat().map(x=>x.username.toLowerCase())).size,accounts.length);
const now=Date.parse('2026-11-13T09:00:00Z');
const group=groups[0];
const q=buildQuery(group,now);
assert(q.includes('since_time:'));
assert(q.includes('-filter:replies'));
assert(q.includes(' OR '));
assert(q.includes('from:'+group[0].username));
assert.equal(monthUtc(now),'2026-11');
let first=reservePlan(null,config,now,false);
assert.equal(first.reason,'no-key');
assert.equal(first.state.reservedMicroUsd,0);
first=reservePlan(null,config,now,true);
assert.equal(first.reason,'reserved');
assert.equal(first.state.pending.handles.length,group.length);
assert.equal(first.state.reservedMicroUsd,X_POLICY.maxReservedMicroUsdPerRequest);
assert.equal(reservePlan(first.state,config,now+3600000,true).reason,'pending-reservation');
const after=finalizeLedger(first.state,{result:{ok:true,returnedCount:20},at:new Date(now).toISOString()});
assert.equal(after.completed,1);
assert.equal(after.verifiedEstimateMicroUsd,3000);
assert.equal(after.pending,null);
assert.equal(reservePlan(after,config,now+30*60000,true).reason,'cooldown');
assert.equal(reservePlan(after,config,now+90*60000,true).reason,'reserved');
let ledger={...after,reservedMicroUsd:1_800_000};
assert.equal(reservePlan(ledger,config,now+10000000,true).reason,'monthly-budget');
ledger={...ledger,paused:true};
assert.equal(reservePlan(ledger,config,now+10000000,true).reason,'provider-paused');
ledger={...after,nextGroupIndex:4};
assert.equal(reservePlan(ledger,config,Date.parse('2026-12-01T09:00:00Z'),true).state.nextGroupIndex,5,
 'Monthly reset preserves the next account group');
const stamp=now-3600000;
const snow=((BigInt(stamp)-1288834974657n)<<22n|123n).toString();
const date=new Date(stamp).toUTCString().replace(' GMT',' +0000');
const author=group[0];
const sample={id:snow,createdAt:date,author:{userName:author.username},text:'Major UFC title fight confirmed after training camp',likeCount:45,retweetCount:3,replyCount:8};
const posts=normalizeTweets({tweets:[sample,{...sample,id:((BigInt(stamp+1)-1288834974657n)<<22n|123n).toString(),author:{userName:'ImposterAccount'}},
 {...sample,id:((BigInt(stamp+2)-1288834974657n)<<22n|123n).toString(),retweeted_tweet:{id:'1'}},
 {...sample,id:((BigInt(stamp+3)-1288834974657n)<<22n|123n).toString(),isReply:true}]},group,now);
assert.equal(posts.length,1,'Only correctly identified original author posts may publish');
assert.equal(posts[0].role,author.role);
assert(posts[0].url.startsWith('https://x.com/'+author.username+'/status/'));
assert.equal(posts[0].engagement.likes,45);
assert.throws(()=>normalizeTweets({tweets:new Array(21).fill(sample)},group,now),/more than/);
assert.equal(mergeXFeed({posts:[]},posts,now).length,1);
assert.equal(mergeXFeed({posts},posts,now).length,1,'Dedupe canonical X URLs');
assert.equal(mergeXFeed({posts},[],now+29*86400_000).length,0,'Archive expiration');
assert.equal(X_POLICY.monthlyUsdLimit,2);
assert(X_POLICY.internalMonthlyReserveMicroUsd<2_000_000);
assert(X_POLICY.maxReservedMicroUsdPerRequest>=3000);
console.log('TwitterAPI.io: tracked original author groups, conservative spend reservations, identity verification, deduplication and expiry passed.');
